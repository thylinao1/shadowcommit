import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const UNICODE_VERSION = "17.0.0";
const CONFUSABLES_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/security/confusables.txt`;
const CORE_PROPERTIES_URL = `https://www.unicode.org/Public/${UNICODE_VERSION}/ucd/DerivedCoreProperties.txt`;
const CONFUSABLES_SHA256 = "091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a";
const CORE_PROPERTIES_SHA256 = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08";

const here = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(here, "../apps/server/src/unicode-confusables.generated.ts");

async function download(url, expectedDigest) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} returned HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const digest = createHash("sha256").update(bytes).digest("hex");
  if (digest !== expectedDigest) {
    throw new Error(`${url} sha256 ${digest}, expected ${expectedDigest}`);
  }
  return bytes.toString("utf8");
}

function codePoints(field) {
  return field.trim().split(/\s+/).map((hex) => String.fromCodePoint(Number.parseInt(hex, 16))).join("");
}

function parseConfusables(text) {
  const entries = [];
  for (const line of text.split("\n")) {
    const body = line.split("#", 1)[0].trim();
    if (!body) continue;
    const fields = body.split(";");
    const source = codePoints(fields[0]);
    const target = codePoints(fields[1]);
    if ([...source].length !== 1) throw new Error(`multi-code-point source in ${line}`);
    // Protected declarations are path regexes over ASCII names. A prototype containing a
    // non-ASCII code point cannot equal one of those names, so omitting it changes no match and
    // keeps the runtime table narrow.
    if (!/^[\x00-\x7f]+$/.test(target)) continue;
    entries.push([source.codePointAt(0), target]);
  }
  return entries.sort((a, b) => a[0] - b[0]);
}

function parseDefaultIgnorables(text) {
  const ranges = [];
  for (const line of text.split("\n")) {
    const body = line.split("#", 1)[0].trim();
    if (!body || !body.includes("; Default_Ignorable_Code_Point")) continue;
    const field = body.split(";", 1)[0].trim();
    const [first, last = first] = field.split("..");
    ranges.push([Number.parseInt(first, 16), Number.parseInt(last, 16)]);
  }
  return ranges;
}

function render(entries, ranges) {
  const rows = entries.map(([source, target]) => `  [0x${source.toString(16)}, ${JSON.stringify(target)}],`).join("\n");
  const rangeRows = ranges.map(([first, last]) => `  [0x${first.toString(16)}, 0x${last.toString(16)}],`).join("\n");
  return `/* This file is generated by scripts/generate-unicode-confusables.mjs. */
/* Source: Unicode 17.0.0 UTS #39 confusables and DerivedCoreProperties data. */

export const UNICODE_SECURITY_VERSION = ${JSON.stringify(UNICODE_VERSION)};
export const UNICODE_CONFUSABLES_SHA256 = ${JSON.stringify(CONFUSABLES_SHA256)};
export const UNICODE_CORE_PROPERTIES_SHA256 = ${JSON.stringify(CORE_PROPERTIES_SHA256)};

const ASCII_PROTOTYPE_BY_CODE_POINT: ReadonlyMap<number, string> = new Map([
${rows}
]);

const DEFAULT_IGNORABLE_RANGES: ReadonlyArray<readonly [number, number]> = [
${rangeRows}
];

export function asciiConfusablePrototype(codePoint: number): string | undefined {
  return ASCII_PROTOTYPE_BY_CODE_POINT.get(codePoint);
}

export function isDefaultIgnorableCodePoint(codePoint: number): boolean {
  return DEFAULT_IGNORABLE_RANGES.some(([first, last]) => codePoint >= first && codePoint <= last);
}
`;
}

const [confusables, coreProperties] = await Promise.all([
  download(CONFUSABLES_URL, CONFUSABLES_SHA256),
  download(CORE_PROPERTIES_URL, CORE_PROPERTIES_SHA256),
]);
const source = render(parseConfusables(confusables), parseDefaultIgnorables(coreProperties));
await fs.writeFile(output, source, "utf8");
console.log(`wrote ${output}`);
